//  Offline geolocation for the destination map. Every answer in this module
//  comes from files in its resource bundle — an IP → country table, country
//  outlines, centroids and a tz → country table — so nothing about where a
//  request went ever leaves the Mac. The files are generated by
//  Scripts/geo/build-geo-resources.py; Resources/PROVENANCE.md says from what.
//

import Foundation

public enum GeoKit {

    /// The credit the data licences ask for. DB-IP's CC BY 4.0 REQUIRES it;
    /// Natural Earth is public domain and gets one anyway. The About/Licenses
    /// screen shows this string verbatim.
    public static let attribution = "IP Geolocation by DB-IP (db-ip.com), CC BY 4.0. World outlines by Natural Earth (public domain)."

    /// The month of the DB-IP snapshot in the bundled table, "YYYY-MM" — nil
    /// only if the table failed to load.
    public static var dataMonth: String? { IPCountryTable.shared?.dataMonth }

    static func resourceURL(_ name: String, extension ext: String) throws -> URL {
        guard let url = Bundle.module.url(forResource: name, withExtension: ext) else {
            throw GeoKitError.resourceMissing("\(name).\(ext)")
        }
        return url
    }
}

public enum GeoKitError: Error, Equatable {
    /// A bundled file is not in the module's resource bundle.
    case resourceMissing(String)
    /// A bundled file does not have the shape the converter writes.
    case malformed(String)
}
