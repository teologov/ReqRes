// swift-tools-version:5.8
// The swift-tools-version declares the minimum version of Swift required to build this package.
import PackageDescription

let package = Package(
    name: "AppServices",
    platforms: [
        .macOS(.v13)
    ],
    products: [
        .library(
            name: "Utils",
            targets: ["Utils"]
        ),
        .library(
            name: "MCPKit",
            targets: ["MCPKit"]
        ),
        .library(
            name: "GeoKit",
            targets: ["GeoKit"]
        ),
        .executable(
            name: "reqres-mcp",
            targets: ["reqres-mcp"]
        )
    ],
    dependencies: [
        .package(name: "Sentry", url: "https://github.com/getsentry/sentry-cocoa", from: "8.41.0"),
        .package(url: "https://github.com/sparkle-project/Sparkle", exact: "2.9.6"),
        .package(url: "https://github.com/modelcontextprotocol/swift-sdk.git", exact: "0.12.0"),
    ],
    targets: [
        .target(
            name: "Utils",
            dependencies: [
                "Sentry",
                "Sparkle"
            ]
        ),
        // The agent bridge's pure, core-agnostic logic: models, redaction,
        // queries, the loopback HTTP bridge and its router. No AppKit, no
        // closed framework — built and tested standalone.
        .target(
            name: "MCPKit",
            dependencies: []
        ),
        // Offline geolocation for the destination map: IP → country (DB-IP Lite,
        // CC BY 4.0), country outlines + centroids (Natural Earth, public
        // domain), tz identifier → country (tz database, public domain).
        // Foundation only. Every answer comes from the bundled resources;
        // nothing about a destination ever leaves the Mac. The resources are
        // generated by Scripts/geo/build-geo-resources.py — never edit them by
        // hand, `--check` verifies they are exactly what the converter emits.
        .target(
            name: "GeoKit",
            dependencies: [],
            resources: [.process("Resources")]
        ),
        // The stdio MCP server clients spawn; thin, everything reusable is in MCPKit.
        .executableTarget(
            name: "reqres-mcp",
            dependencies: [
                "MCPKit",
                .product(name: "MCP", package: "swift-sdk"),
            ],
            exclude: ["Info.plist", "reqres-mcp.entitlements"],
            // The helper runs SANDBOXED (it must be an app-group member to read
            // the handshake in the group container), and a sandboxed tool is
            // killed at exec unless a bundle identifier is embedded in it.
            linkerSettings: [
                .unsafeFlags(["-Xlinker", "-sectcreate", "-Xlinker", "__TEXT", "-Xlinker", "__info_plist",
                              "-Xlinker", "Sources/reqres-mcp/Info.plist"]),
            ]
        ),
        // Pure-logic tests, runnable with a plain `swift test` — no Xcode
        // scheme, no closed core framework, no signing.
        // Also depends on MCPKit for ONE assertion: that the search token's
        // word for an unattributed session (`TrafficSearchAppMatch.unknown`)
        // is the App column's (`ProcessIdentity.unknownLabel`). Utils cannot
        // import MCPKit itself without dragging Sentry/Sparkle into the
        // helper's dependency graph, so the test target is where both meet.
        .testTarget(
            name: "UtilsTests",
            dependencies: ["Utils", "MCPKit"]
        ),
        .testTarget(
            name: "MCPKitTests",
            dependencies: ["MCPKit"]
        ),
        // Fixtures/ip-samples.csv is sampled from the same DB-IP CSV the binary
        // table was built from, so the decoder is checked against its own data.
        .testTarget(
            name: "GeoKitTests",
            dependencies: ["GeoKit"],
            resources: [.copy("Fixtures")]
        ),
    ],
)
